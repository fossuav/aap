#!/usr/bin/env python3
# AP_FLAKE8_CLEAN
"""Clean up what agent sessions leave behind around an ArduPilot checkout.

A scratch worktree costs far more than its checkout: it carries its own build
tree, the autotest helper gives it a ../buildlogs-<name> log tree, and the main
repository keeps a clone of every submodule for it under
.git/worktrees/<name>/modules. This lists those worktrees and the local
branches nothing needs, works out what removing each would lose, and removes
them only after saving that.

Usage:
    python3 cleanup.py survey   (--only NAME[,NAME...] | --sweep) [--keep-days N] [--plan FILE]
    python3 cleanup.py branches [--only NAME[,NAME...] | --sweep] [--keep-days N]
                                [--protect REGEX] [--pr-repo OWNER/REPO] [--plan FILE]
    python3 cleanup.py apply    --plan FILE [--backup-dir DIR] [--dry-run]

survey and branches only read. apply re-checks every entry against the
checkout as it is now, and skips anything that changed since the plan was made.
"""
import argparse
import datetime
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import time

# Installed by the playbook installers; regenerated by them, never worth saving.
PLAYBOOK_FILE = re.compile(
    r'(^|/)(\.claude|\.codex|\.gemini)/$'
    r'|(^|/)(CLAUDE|CODEX|GEMINI)(_[A-Z_]+)?\.md(\.bak)?$'
    r'|(^|/)AGENTS(\.override)?\.md(\.bak)?$')
# A worktree with more than this to save is left for the user to look at.
REVIEW_UNTRACKED_BYTES = 100 * 1024 * 1024
# A plan older than this describes a tree that has probably moved on.
PLAN_MAX_AGE_S = 24 * 3600


# git status otherwise refreshes the index, which would make every worktree it
# looks at read as touched just now, and apply would then skip them all.
GIT_ENV = dict(os.environ, GIT_OPTIONAL_LOCKS="0")


def git(args, cwd, stdin=None, timeout=None):
    """Run git, returning the CompletedProcess (never raises on failure)."""
    return subprocess.run(["git"] + args, cwd=cwd, input=stdin, capture_output=True,
                          text=True, timeout=timeout, env=GIT_ENV)


def du_kb(path):
    """Disk usage of path in KiB, 0 if it does not exist."""
    if not os.path.lexists(path):
        return 0
    r = subprocess.run(["du", "-sk", path], capture_output=True, text=True)
    try:
        return int(r.stdout.split()[0])
    except (IndexError, ValueError):
        return 0


def gb(kb):
    return "%.1fG" % (kb / 1048576.0)


def common_dir(path):
    """Absolute git common dir of the repository containing path, or None."""
    r = git(["rev-parse", "--git-common-dir"], path)
    if r.returncode != 0:
        return None
    return os.path.abspath(os.path.join(path, r.stdout.strip()))


def main_repo(path):
    """Top level of the main worktree of the repository containing path."""
    cd = common_dir(path)
    if cd is None or os.path.basename(cd) != ".git":
        return None
    return os.path.dirname(cd)


def worktree_entries(repo):
    """Parsed 'git worktree list --porcelain' for repo, main worktree first."""
    out = git(["worktree", "list", "--porcelain"], repo).stdout
    entries, cur = [], {}
    for line in out.splitlines():
        if not line:
            if cur:
                entries.append(cur)
            cur = {}
            continue
        key, _, val = line.partition(" ")
        cur[key] = val if val else True
    if cur:
        entries.append(cur)
    return entries


def gitdir_of(path):
    """The admin dir a linked worktree's .git file points at, or None."""
    try:
        with open(os.path.join(path, ".git")) as f:
            for line in f:
                if line.startswith("gitdir:"):
                    return os.path.abspath(os.path.join(path, line.split(":", 1)[1].strip()))
    except OSError:
        pass
    return None


def process_cwds():
    """Working directories of every running process (Linux /proc), or None."""
    if not os.path.isdir("/proc/self"):
        return None
    cwds = set()
    for pid in os.listdir("/proc"):
        if pid.isdigit():
            try:
                cwds.add(os.readlink("/proc/%s/cwd" % pid))
            except OSError:
                pass
    return cwds


def in_use(path, cwds):
    if cwds is None:
        return False
    return any(c == path or c.startswith(path + "/") for c in cwds)


def buildlogs_of(path):
    """The autotest log tree run_autotest.py gives this checkout."""
    return os.path.join(os.path.dirname(path), "buildlogs-%s" % os.path.basename(path))


def last_touched(path, gitdir):
    """Latest mtime among the places a session's work shows up."""
    cands = [path, os.path.join(path, "build"), buildlogs_of(path)]
    if gitdir:
        cands += [os.path.join(gitdir, f) for f in ("index", "HEAD", os.path.join("logs", "HEAD"))]
    times = []
    for c in cands:
        try:
            times.append(os.stat(c).st_mtime)
        except OSError:
            pass
    return max(times) if times else 0


def untracked_to_save(path):
    """Untracked, non-ignored entries worth saving: not playbooks, not waf build trees."""
    out = git(["status", "--porcelain", "--untracked-files=normal", "--ignore-submodules=all"], path).stdout
    keep = []
    for line in out.splitlines():
        if not line.startswith("?? "):
            continue
        rel = line[3:].strip('"')
        if PLAYBOOK_FILE.search(rel):
            continue
        full = os.path.join(path, rel)
        if rel.endswith("/") and os.path.isdir(os.path.join(full, "c4che")):
            continue  # a waf build tree configured with -o/--out
        if os.path.basename(rel.rstrip("/")).startswith(".lock-waf"):
            continue
        keep.append(rel.rstrip("/"))
    return keep


def inspect(path, repo, keep_s, cwds, now):
    """Everything apply needs to know about one linked worktree."""
    e = {"name": os.path.basename(path), "path": path, "repo": repo, "keep": False, "why": ""}
    gitdir = gitdir_of(path)
    if not os.path.isdir(path) or gitdir is None:
        e.update(action="prune", why="directory gone; registration only")
        return e
    e["gitdir"] = gitdir
    e["head"] = git(["rev-parse", "HEAD"], path).stdout.strip()
    e["branch"] = git(["symbolic-ref", "-q", "--short", "HEAD"], path).stdout.strip() or None
    e["touched"] = last_touched(path, gitdir)
    if os.path.exists(os.path.join(gitdir, "locked")):
        e.update(action="keep", why="locked")
        return e
    if in_use(path, cwds):
        e.update(action="keep", why="a process is running inside it")
        return e
    if now - e["touched"] < keep_s:
        e.update(action="keep", why="touched %s" % time.strftime("%Y-%m-%d %H:%M", time.localtime(e["touched"])))
        return e
    status = git(["status", "--porcelain", "--untracked-files=no"], path).stdout.splitlines()
    e["dirty"] = len(status)
    e["unique"] = 0
    if e["branch"] is None:
        r = git(["rev-list", "--count", "HEAD", "--not", "--branches", "--remotes", "--tags"], path)
        e["unique"] = int(r.stdout.strip() or 0)
    e["untracked"] = untracked_to_save(path)
    e["untracked_kb"] = sum(du_kb(os.path.join(path, u)) for u in e["untracked"])
    e["kb"] = du_kb(path) + du_kb(gitdir) + du_kb(buildlogs_of(path))
    if e["untracked_kb"] * 1024 > REVIEW_UNTRACKED_BYTES:
        e.update(action="review", why="%s of untracked files to save; look first" % gb(e["untracked_kb"]))
        return e
    saves = []
    if e["dirty"]:
        saves.append("diff of %d files" % e["dirty"])
    if e["unique"]:
        saves.append("branch for %d commits on no branch" % e["unique"])
    if e["untracked"]:
        saves.append("%d untracked" % len(e["untracked"]))
    e.update(action="remove", why=("save " + ", ".join(saves)) if saves else "nothing to save")
    return e


def sweep_repos(root):
    """Main repositories of every checkout directly under root."""
    repos = set()
    for name in sorted(os.listdir(root)):
        p = os.path.join(root, name)
        g = os.path.join(p, ".git")
        if os.path.isdir(g):
            repos.add(p)
        elif os.path.isfile(g):
            gd = gitdir_of(p)
            if gd and os.path.isdir(gd):
                r = main_repo(p)
                if r:
                    repos.add(r)
    return sorted(repos)


def resolve_only(names, root):
    """Paths for --only, which takes worktree directory names or paths."""
    paths = []
    for n in names:
        p = os.path.abspath(n if os.sep in n else os.path.join(root, n))
        paths.append(p)
    return paths


def cmd_survey(args):
    here = main_repo(os.getcwd())
    if here is None:
        sys.exit("run from inside a git checkout")
    root = os.path.abspath(args.root or os.path.dirname(here))
    keep_s = args.keep_days * 86400
    cwds = process_cwds()
    now = time.time()
    targets = []  # (path, repo)
    if args.sweep:
        for repo in sweep_repos(root) + [here]:
            for ent in worktree_entries(repo)[1:]:
                targets.append((ent["worktree"], repo))
    elif args.only:
        for p in resolve_only(args.only.split(","), root):
            repo = main_repo(p) if os.path.isdir(p) else None
            if repo is None or os.path.realpath(repo) == os.path.realpath(p):
                print("not a linked worktree, left alone: %s" % p)
                continue
            targets.append((p, repo))
    else:
        sys.exit("name the worktrees this session made with --only, or pass --sweep")
    seen, entries = set(), []
    for p, repo in targets:
        if p in seen:
            continue
        seen.add(p)
        entries.append(inspect(p, repo, keep_s, cwds, now))
    if cwds is None:
        print("note: no /proc here, so worktrees in use by a process cannot be detected")

    order = {"remove": 0, "prune": 1, "review": 2, "keep": 3}
    entries.sort(key=lambda e: (order[e["action"]], e["path"]))
    for e in entries:
        where = e.get("branch") or ("detached:%s" % e["head"][:10] if e.get("head") else "-")
        print("%-7s %7s  %-32s %-22s %-32s %s" % (
            e["action"], gb(e.get("kb", 0)) if e.get("kb") else "-", e["name"],
            os.path.basename(e["repo"]), where, e["why"]))
    for act in ("remove", "prune", "review", "keep"):
        sel = [e for e in entries if e["action"] == act]
        if sel:
            print("%s: %d worktrees%s" % (act, len(sel), (", " + gb(sum(e.get("kb", 0) for e in sel)))
                                          if act == "remove" else ""))
    plan = {"kind": "worktrees", "created": now, "root": root, "entries": entries}
    with open(args.plan, "w") as f:
        json.dump(plan, f, indent=1)
    print("plan: %s" % args.plan)


def live_head_shas(repo):
    """Commit ids of every branch head that exists on a remote now (ls-remote)."""
    shas, failed = set(), []
    for remote in git(["remote"], repo).stdout.split():
        try:
            r = git(["ls-remote", "--heads", remote], repo, timeout=60)
        except subprocess.TimeoutExpired:
            failed.append(remote)
            continue
        if r.returncode != 0:
            failed.append(remote)
            continue
        shas.update(line.split()[0] for line in r.stdout.splitlines() if line.strip())
    if shas:
        r = git(["cat-file", "--batch-check"], repo, stdin="\n".join(sorted(shas)) + "\n")
        shas = {line.split()[0] for line in r.stdout.splitlines() if line.endswith(" commit") or " commit " in line}
    return shas, failed


def github_repo(url):
    m = re.search(r'github\.com[:/]([^/]+/[^/]+?)(\.git)?$', url.strip())
    return m.group(1) if m else None


def open_pr_heads(repo, pr_repos):
    """Head branch names of the user's open PRs, or None if gh could not say."""
    if not pr_repos:
        for remote in ("upstream", "origin"):
            r = git(["remote", "get-url", remote], repo)
            if r.returncode == 0 and github_repo(r.stdout):
                pr_repos.append(github_repo(r.stdout))
    if not pr_repos:
        return set()
    heads = set()
    for pr_repo in pr_repos:
        try:
            r = subprocess.run(["gh", "pr", "list", "--repo", pr_repo, "--author", "@me", "--state", "open",
                                "--limit", "500", "--json", "headRefName", "--jq", ".[].headRefName"],
                               capture_output=True, text=True, timeout=120)
        except (OSError, subprocess.TimeoutExpired):
            return None
        if r.returncode != 0:
            return None
        heads.update(r.stdout.split())
    return heads


def cmd_branches(args):
    here = main_repo(os.getcwd())
    if here is None:
        sys.exit("run from inside a git checkout")
    root = os.path.abspath(args.root or os.path.dirname(here))
    repos = sorted(set(sweep_repos(root) + [here])) if args.sweep else [here]
    only = set(args.only.split(",")) if args.only else None
    protect = re.compile("|".join(["^(master|main)$"] + args.protect))
    keep_s = args.keep_days * 86400
    now = time.time()
    entries = []
    for repo in repos:
        cdir = common_dir(repo)
        checked = {e["branch"][len("refs/heads/"):] for e in worktree_entries(repo) if "branch" in e}
        live, failed = live_head_shas(repo)
        prs = open_pr_heads(repo, list(args.pr_repo))
        kept = {}
        out = git(["for-each-ref", "--format=%(refname)%09%(objectname)%09%(committerdate:unix)", "refs/heads"],
                  repo).stdout
        print("== %s" % repo)
        if failed:
            print("  remotes not reachable, their branches count as not on a remote: %s" % " ".join(failed))
        if prs is None:
            print("  open PR heads could not be listed (gh); each candidate is flagged")
        for line in out.splitlines():
            ref, sha, cdate = line.split("\t")
            name = ref[len("refs/heads/"):]
            if only is not None and name not in only:
                continue
            reason = None
            if name in checked:
                reason = "checked out"
            elif protect.search(name):
                reason = "protected name"
            elif prs is not None and name in prs:
                reason = "open PR head"
            else:
                log = os.path.join(cdir, "logs", ref)
                updated = os.stat(log).st_mtime if os.path.exists(log) else float(cdate or 0)
                if now - updated < keep_s:
                    reason = "updated recently"
                else:
                    r = git(["rev-list", "-n", "1", "--stdin"], repo,
                            stdin="%s\n%s\n" % (sha, "\n".join("^" + s for s in live)))
                    if r.returncode != 0 or r.stdout.strip():
                        reason = "has commits on no live remote"
            if reason:
                kept[reason] = kept.get(reason, 0) + 1
                continue
            e = {"repo": repo, "ref": ref, "name": name, "sha": sha, "updated": updated,
                 "pr_unknown": prs is None}
            entries.append(e)
            print("  delete  %-48s %s  updated %s%s" % (name, sha[:10], time.strftime("%Y-%m-%d", time.localtime(updated)),
                                                        "  (PR status unknown)" if prs is None else ""))
        for reason, n in sorted(kept.items()):
            print("  keep    %d: %s" % (n, reason))
    print("delete: %d branches" % len(entries))
    plan = {"kind": "branches", "created": now, "root": root, "entries": entries}
    with open(args.plan, "w") as f:
        json.dump(plan, f, indent=1)
    print("plan: %s" % args.plan)


def unique_backup_branch(repo, name):
    base = "wt-backup/%s" % name
    cand, n = base, 1
    while git(["rev-parse", "--verify", "-q", "refs/heads/" + cand], repo).returncode == 0:
        n += 1
        cand = "%s-%d" % (base, n)
    return cand


def apply_worktree(e, backup, dry, cwds):
    """Re-check one worktree, save what removing it would lose, remove it, verify."""
    path, repo, name = e["path"], e["repo"], e["name"]
    if e["action"] == "prune":
        return "PRUNE   %s (registration only)" % name
    gitdir = gitdir_of(path)
    if gitdir != e.get("gitdir") or not os.path.isdir(path):
        return "SKIP    %s: no longer the worktree surveyed" % name
    if git(["rev-parse", "HEAD"], path).stdout.strip() != e["head"]:
        return "SKIP    %s: HEAD moved since the survey" % name
    if last_touched(path, gitdir) > e["touched"] + 1:
        return "SKIP    %s: touched since the survey" % name
    if in_use(path, cwds):
        return "SKIP    %s: a process is running inside it" % name
    if os.path.exists(os.path.join(gitdir, "locked")):
        return "SKIP    %s: locked" % name
    dirty = len(git(["status", "--porcelain", "--untracked-files=no"], path).stdout.splitlines())
    untracked = untracked_to_save(path)
    if dirty != e["dirty"] or sorted(untracked) != sorted(e["untracked"]):
        return "SKIP    %s: its changes differ from the survey" % name
    if dry:
        return "WOULD   remove %s (%s)" % (name, e["why"])

    saved = []
    if dirty:
        with open(os.path.join(backup, name + ".status"), "w") as f:
            f.write(git(["status", "--porcelain", "--untracked-files=no"], path).stdout)
        patch = os.path.join(backup, name + ".patch")
        with open(patch, "wb") as f:
            f.write(subprocess.run(["git", "diff", "HEAD", "--binary"], cwd=path, capture_output=True,
                                   env=GIT_ENV).stdout)
        if os.path.getsize(patch) == 0:
            return "STOP    %s: the diff backup came out empty" % name
        saved.append("patch")
    if e["branch"] is None and e["unique"]:
        b = unique_backup_branch(repo, name)
        git(["branch", b, e["head"]], repo)
        if git(["rev-parse", "refs/heads/" + b], repo).stdout.strip() != e["head"]:
            return "STOP    %s: could not create backup branch %s" % (name, b)
        saved.append("branch " + b)
    if untracked:
        tgz = os.path.join(backup, name + "-untracked.tgz")
        with tarfile.open(tgz, "w:gz") as t:
            for u in untracked:
                t.add(os.path.join(path, u), arcname=u)
        with tarfile.open(tgz) as t:
            got = {m.name for m in t.getmembers()}
        if not set(untracked) <= got:
            return "STOP    %s: the untracked backup is incomplete" % name
        saved.append("untracked")
    with open(os.path.join(backup, "removed_worktrees.tsv"), "a") as f:
        f.write("%s\t%s\t%s\t%s\t%s\n" % (name, path, repo, e["branch"] or "detached", e["head"]))

    r = git(["worktree", "remove", "--force", path], repo)
    if r.returncode != 0:
        return "FAIL    %s: %s" % (name, r.stderr.strip().replace("\n", " "))
    logs = buildlogs_of(path)
    if os.path.isdir(logs) and not os.path.islink(logs) and not in_use(logs, cwds):
        shutil.rmtree(logs, ignore_errors=True)
    left = [p for p in (path, gitdir, logs) if os.path.lexists(p)]
    if left:
        return "WARN    %s: removed, but left behind: %s" % (name, " ".join(left))
    return "REMOVED %s%s" % (name, (" (saved: %s)" % ", ".join(saved)) if saved else "")


def apply_branch(e, backup, dry):
    repo, ref, sha, name = e["repo"], e["ref"], e["sha"], e["name"]
    if git(["rev-parse", "--verify", "-q", ref], repo).stdout.strip() != sha:
        return "SKIP    %s: moved since the survey" % name
    checked = {w.get("branch") for w in worktree_entries(repo)}
    if ref in checked:
        return "SKIP    %s: checked out now" % name
    if dry:
        return "WOULD   delete %s (%s)" % (name, sha[:10])
    with open(os.path.join(backup, "deleted_branches.tsv"), "a") as f:
        f.write("%s\t%s\t%s\n" % (repo, name, sha))
    r = git(["update-ref", "-d", ref, sha], repo)
    if r.returncode != 0 or git(["rev-parse", "--verify", "-q", ref], repo).returncode == 0:
        return "FAIL    %s: %s" % (name, r.stderr.strip())
    return "DELETED %s" % name


def cmd_apply(args):
    with open(args.plan) as f:
        plan = json.load(f)
    age = time.time() - plan["created"]
    if age > PLAN_MAX_AGE_S:
        sys.exit("plan is %.0f h old; survey again" % (age / 3600))
    backup = os.path.abspath(args.backup_dir or os.path.join(
        plan["root"], "cleanup-backups-%s" % datetime.date.today().strftime("%Y%m%d")))
    if not args.dry_run:
        os.makedirs(backup, exist_ok=True)
    before = shutil.disk_usage(plan["root"]).used
    results = []
    if plan["kind"] == "worktrees":
        cwds = process_cwds()
        prune = set()
        for e in plan["entries"]:
            if e["action"] not in ("remove", "prune"):
                continue
            res = apply_worktree(e, backup, args.dry_run, cwds)
            if e["action"] == "prune":
                prune.add(e["repo"])
            print(res)
            results.append(res.split()[0])
        for repo in sorted(prune):
            if args.dry_run:
                print(git(["worktree", "prune", "--dry-run", "-v"], repo).stderr.strip())
            else:
                git(["worktree", "prune"], repo)
    else:
        for e in plan["entries"]:
            res = apply_branch(e, backup, args.dry_run)
            print(res)
            results.append(res.split()[0])
    counts = {k: results.count(k) for k in sorted(set(results))}
    print("summary: %s" % ", ".join("%s %d" % kv for kv in counts.items()))
    if not args.dry_run:
        freed = (before - shutil.disk_usage(plan["root"]).used) / 1024.0
        print("freed about %s; backups in %s" % (gb(max(freed, 0)), backup))
        try:
            with open("/proc/version") as f:
                if "microsoft" in f.read().lower():
                    print("WSL: the virtual disk does not shrink by itself; compact ext4.vhdx from Windows"
                          " after 'wsl --shutdown' (Optimize-VHD, or diskpart 'compact vdisk')")
        except OSError:
            pass


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("survey", help="list worktrees and what removing each would lose")
    s.add_argument("--only", help="worktree directory names or paths, comma separated")
    s.add_argument("--sweep", action="store_true", help="every worktree of every checkout beside this one")
    s.add_argument("--root", help="directory holding the checkouts (default: this checkout's parent)")
    s.add_argument("--keep-days", type=float, default=2, help="keep anything touched this recently (default 2)")
    s.add_argument("--plan", default="cleanup-worktrees.json")
    b = sub.add_parser("branches", help="list local branches safe to delete")
    b.add_argument("--only", help="branch names, comma separated")
    b.add_argument("--sweep", action="store_true", help="every checkout beside this one")
    b.add_argument("--root")
    b.add_argument("--keep-days", type=float, default=2)
    b.add_argument("--protect", action="append", default=[], help="regex of branch names never to delete")
    b.add_argument("--pr-repo", action="append", default=[], help="OWNER/REPO to read open PR heads from")
    b.add_argument("--plan", default="cleanup-branches.json")
    a = sub.add_parser("apply", help="carry out a plan")
    a.add_argument("--plan", required=True)
    a.add_argument("--backup-dir")
    a.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    {"survey": cmd_survey, "branches": cmd_branches, "apply": cmd_apply}[args.cmd](args)


if __name__ == "__main__":
    main()
