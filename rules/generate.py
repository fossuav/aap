#!/usr/bin/env python3
"""
Write one page per confirmed architectural rule, and the rules index in the
README, from the rule text in the Claude playbooks.

The playbook is the only source of a rule's wording: the pages are generated
so they never say anything the confirmed text does not. A rule is found by
its "(ARCH-n, confirmed YYYY-MM-DD):" marker, either after a bold title on a
line of its own, with the rule's bullets below it, or inside a sentence,
where the clause before the marker is the title.

Re-run after confirming or editing a rule. --check writes nothing and exits 1
if a page or the index has fallen behind the playbook.

AP_FLAKE8_CLEAN
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PLAYBOOKS = ROOT / 'claude'
RULES = ROOT / 'rules'
README = ROOT / 'README.md'

INDEX_BEGIN = '<!-- rules index: generated by rules/generate.py -->'
INDEX_END = '<!-- end of rules index -->'
PAGE_HEADER = '<!-- Generated by rules/generate.py from {src}. Edit the playbook and re-run it; edits here are lost. -->'
PR_URL = 'https://github.com/ArduPilot/ardupilot/pull/'

MARKER = re.compile(r'\(ARCH-(\d+), confirmed (\d{4}-\d{2}-\d{2})\):')
TITLED = re.compile(r'^\*\*(.+?)\*\* ' + MARKER.pattern + r'\s*$')
BOLD_LABEL = re.compile(r'^\*\*[^*]+\*\*\s*')


class Rule:
    def __init__(self, number, date, title, body, source, section):
        self.number = number
        self.date = date
        self.title = title
        self.body = body
        self.source = source
        self.section = section

    @property
    def name(self):
        return f'ARCH-{self.number}'


def sentence_case(title):
    '''The playbook's bold titles are in title case; the index reads better in sentence case.
    Acronyms and identifiers keep their case.'''
    def keep(part):
        letters = re.sub(r'[^A-Za-z]', '', part)
        return '_' in part or (len(letters) > 1 and letters.isupper())
    words = title.split(' ')
    rest = ['-'.join(p if keep(p) else p.lower() for p in w.split('-')) for w in words[1:]]
    return ' '.join([words[0]] + rest)


def slug(heading):
    '''GitHub's anchor for a markdown heading.'''
    text = re.sub(r'[*_`]', '', heading).strip().lower()
    return re.sub(r'[^a-z0-9 -]', '', text).replace(' ', '-')


def parse(path):
    lines = path.read_text().splitlines()
    rules = []
    section = None
    for i, line in enumerate(lines):
        heading = re.match(r'^#+\s+(.*)', line)
        if heading:
            section = heading.group(1).strip()
            continue
        m = MARKER.search(line)
        if not m:
            continue
        number, date = int(m.group(1)), m.group(2)
        titled = TITLED.match(line)
        if titled:
            title = titled.group(1)
            body = []
            for following in lines[i + 1:]:
                if not following.strip():
                    break
                body.append(following)
        else:
            prefix = BOLD_LABEL.sub('', re.sub(r'^\s*-\s+', '', line[:m.start()])).rstrip()
            title = prefix.split('. ')[-1]
            rest = line[m.end():].strip()
            body = [rest[:1].upper() + rest[1:]]
        if not body or not title:
            sys.exit(f'{path.relative_to(ROOT)}:{i + 1}: ARCH-{number} has no title or no text')
        rules.append(Rule(number, date, title, '\n'.join(body), path, section))
    return rules


def linkify(text, known):
    '''Link ArduPilot PR numbers and other rules, leaving code spans alone.'''
    def one(segment):
        segment = re.sub(r'(?<![\w/\[])#(\d{3,6})\b', lambda m: f'[#{m.group(1)}]({PR_URL}{m.group(1)})', segment)
        return re.sub(r'(?<![\w\[])ARCH-(\d+)\b',
                      lambda m: f'[ARCH-{m.group(1)}](ARCH-{m.group(1)}.md)' if int(m.group(1)) in known else m.group(0),
                      segment)
    parts = re.split(r'(`[^`]*`)', text)
    return ''.join(p if p.startswith('`') else one(p) for p in parts)


def playbook_name(path):
    rel = path.relative_to(PLAYBOOKS)
    return 'the root playbook' if len(rel.parts) == 1 else f'the {rel.parent.name} playbook'


def page(rule, known):
    src = rule.source.relative_to(ROOT).as_posix()
    where = playbook_name(rule.source)
    if rule.section:
        where += f', under [{rule.section}](../{src}#{slug(rule.section)})'
    return '\n'.join([
        PAGE_HEADER.format(src=src),
        '',
        f'# {rule.name}: {sentence_case(rule.title)}',
        '',
        linkify(rule.body, known),
        '',
        f'Confirmed {rule.date}. Part of {where}. [All architectural rules](../README.md#architectural-rules)',
        '',
    ])


def index(rules):
    rows = ['| Rule | Principle | Confirmed |', '|------|-----------|-----------|']
    rows += [f'| [{r.name}](rules/{r.name}.md) | {sentence_case(r.title)} | {r.date} |' for r in rules]
    return '\n'.join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--check', action='store_true', help='write nothing; exit 1 if anything is out of date')
    args = parser.parse_args()

    rules = []
    for path in sorted(PLAYBOOKS.rglob('*.md')):
        rules += parse(path)
    rules.sort(key=lambda r: r.number)
    numbers = [r.number for r in rules]
    duplicates = sorted({n for n in numbers if numbers.count(n) > 1})
    if duplicates:
        sys.exit('confirmed in more than one place: ' + ', '.join(f'ARCH-{n}' for n in duplicates))
    known = set(numbers)

    wanted = {RULES / f'{r.name}.md': page(r, known) for r in rules}
    readme = README.read_text()
    if INDEX_BEGIN not in readme or INDEX_END not in readme:
        sys.exit(f'README.md has lost its index markers: {INDEX_BEGIN} ... {INDEX_END}')
    head, rest = readme.split(INDEX_BEGIN, 1)
    tail = rest.split(INDEX_END, 1)[1]
    wanted[README] = f'{head}{INDEX_BEGIN}\n{index(rules)}\n{INDEX_END}{tail}'

    stale = [p for p in RULES.glob('ARCH-*.md') if p not in wanted and p.read_text().startswith('<!-- Generated by')]
    changed = [p for p, text in wanted.items() if not p.exists() or p.read_text() != text]

    if args.check:
        for p in changed + stale:
            print(f'out of date: {p.relative_to(ROOT)}')
        return 1 if changed or stale else 0
    for p in changed:
        p.write_text(wanted[p])
        print(f'wrote {p.relative_to(ROOT)}')
    for p in stale:
        p.unlink()
        print(f'removed {p.relative_to(ROOT)}: no longer a confirmed rule')
    print(f'{len(rules)} rules: ' + ', '.join(r.name for r in rules))
    return 0


if __name__ == '__main__':
    sys.exit(main())
